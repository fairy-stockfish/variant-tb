#!/usr/bin/env python3
"""
Generate Makruk, Cambodian or ASEAN tablebases (see docs/variants/) in
dependency order.

Each material combination is generated once, with the stronger side as
white. Tables are processed by number of pieces and, for the same number
of pieces, by number of pawns, so that the subtables reached by captures
and promotions always exist.

Requires the generators of the variant (mtbgen/mtbgenp, cmtbgen,
astbgen/astbgenp, and the verifiers for --verify) in $PATH or --bindir.
Tables are written to the current directory, which is also used as the
path for subtables (MKTBPATH, CMTBPATH or ASTBPATH).
"""
import argparse
import os
import subprocess
import time
from itertools import combinations_with_replacement
from pathlib import Path

PIECES = ["R", "S", "N", "M", "P"]  # order used in table names

# program prefix, file suffixes and path variable of each variant
VARIANTS = {
    "makruk": ("mtb", ".mkw", ".mkz", "MKTBPATH"),
    "cambodian": ("cmtb", ".cmw", ".cmz", "CMTBPATH"),
    "asean": ("astb", ".asw", ".asz", "ASTBPATH"),
}
VALUE = {"R": 5, "S": 4, "N": 3, "M": 2, "P": 1}


def sides(max_len):
    for k in range(0, max_len + 1):
        for combo in combinations_with_replacement(PIECES, k):
            yield "".join(combo)


def strength(side):
    return (len(side), sorted((VALUE[p] for p in side), reverse=True))


def tables(min_pcs, max_pcs):
    res = set()
    for w in sides(max_pcs - 2):
        for b in sides(max_pcs - 2 - len(w)):
            n = 2 + len(w) + len(b)
            if n < max(3, min_pcs) or n > max_pcs:
                continue
            if strength(w) < strength(b):
                w2, b2 = b, w
            else:
                w2, b2 = w, b
            res.add((n, (w2 + b2).count("P"), "K" + w2 + "vK" + b2))
    return [t for _, _, t in sorted(res)]


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--variant", choices=sorted(VARIANTS), default="makruk")
    ap.add_argument("--threads", type=int, default=1)
    ap.add_argument("--min", dest="min_pcs", type=int, default=3)
    ap.add_argument("--max", dest="max_pcs", type=int, default=4)
    ap.add_argument("--bindir", default="", help="directory of mtbgen/mtbgenp")
    ap.add_argument("--list", action="store_true", help="only list the tables")
    ap.add_argument("--stats", help="append resource usage per table to this CSV file")
    ap.add_argument("--verify", action="store_true",
                    help="verify each table with mtbver/mtbverp after generating it")
    ap.add_argument("--only", nargs="+", metavar="TABLE",
                    help="process only these tables, in the given order")
    args = ap.parse_args()

    prefix, wdl_suffix, dtz_suffix, path_var = VARIANTS[args.variant]
    os.environ.setdefault(path_var, ".")
    # tables recorded in the stats file have been verified (if --verify was
    # given), so that an interrupted run can be resumed
    recorded = set()
    if args.stats and Path(args.stats).exists():
        with open(args.stats) as f:
            recorded = {line.split(",")[0] for line in f}
    for tb in args.only or tables(args.min_pcs, args.max_pcs):
        if args.list:
            print(tb)
            continue
        pawns = "P" in tb
        if Path(tb + dtz_suffix).exists():
            if not (args.verify and args.stats) or tb in recorded:
                continue
            # generated by an interrupted run, but not verified yet
            wall = cpu = rss = None
        else:
            # Cambodian pawnful tables are generated by the counting generator
            prog = prefix + ("genp" if pawns and args.variant != "cambodian" else "gen")
            wall, cpu, rss = run(args, [prog, "-t", str(args.threads), tb])
            if wall is None:
                raise SystemExit("Generating %s failed" % tb)
        vwall = vcpu = ""
        verified = ""
        if args.verify:
            if pawns and args.variant != "cambodian" and is_symmetric(tb):
                # the pawnful verifier cannot handle symmetric material
                verified = "skipped"
            else:
                prog = prefix + ("verp" if pawns and args.variant != "cambodian" else "ver")
                vwall, vcpu, _ = run(args, [prog, "-t", str(args.threads), tb])
                if vwall is None:
                    raise SystemExit("Verifying %s failed" % tb)
                verified = "ok"
                vwall, vcpu = "%.1f" % vwall, "%.1f" % vcpu
        if args.stats:
            new = not Path(args.stats).exists()
            with open(args.stats, "a") as f:
                if new:
                    f.write("table,pieces,wall_s,cpu_s,maxrss_mb,wdl_bytes,"
                            "dtz_bytes,verified,verify_wall_s,verify_cpu_s\n")
                fmt = lambda x: "" if x is None else "%.1f" % x
                f.write("%s,%d,%s,%s,%s,%d,%d,%s,%s,%s\n" % (
                    tb, len(tb) - 1, fmt(wall), fmt(cpu), fmt(rss),
                    Path(tb + wdl_suffix).stat().st_size,
                    Path(tb + dtz_suffix).stat().st_size, verified, vwall, vcpu))


def is_symmetric(tb):
    w, b = tb.split("v")
    return w == b


def run(args, cmd):
    """Run a tool; returns (wall s, cpu s, peak rss MB), or Nones on failure."""
    cmd[0] = os.path.join(args.bindir, cmd[0])
    print("$ " + " ".join(cmd), flush=True)
    t0 = time.time()
    proc = subprocess.Popen(cmd)
    _, status, ru = os.wait4(proc.pid, 0)
    if os.waitstatus_to_exitcode(status) != 0:
        return None, None, None
    return time.time() - t0, ru.ru_utime + ru.ru_stime, ru.ru_maxrss / 1024


if __name__ == "__main__":
    main()
